// 2. FABRIC HELPER & LAYER LOCKING ENGINE
// =========================================================================
function applyStrictLayerLocks(fabricObj) {
  if (!fabricObj) return;
  fabricObj.set({
    lockMovementX: true,
    lockMovementY: true,
    lockRotation: true,
    lockScalingX: true,
    lockScalingY: true,
    hasControls: false,
    hasBorders: false,
    hoverCursor: fabricObj.role === "color_segment" ? "pointer" : "default",
  });

  if (fabricObj.type === "text" || fabricObj.role === "background_art") {
    fabricObj.set({ selectable: false, evented: false });
  } else if (fabricObj.role === "color_segment") {
    fabricObj.set({ selectable: false, evented: true });
  }
}

function clearCanvasForTemplate() {
  if (!canvas) return;
  canvas.clear();
  canvas.setBackgroundColor("#ffffff", canvas.renderAll.bind(canvas));
  setMode("select");
}

function drawHeaderInstructionBlock(message, hexColor) {
  const info = new fabric.Textbox(message, {
    left: PAGE_WIDTH / 2,
    top: 35,
    width: PAGE_WIDTH - 80,
    originX: "center",
    fontSize: 28,
    fontFamily: "Fredoka",
    fontWeight: "900",
    fill: hexColor,
    textAlign: "center",
    role: "background_art",
  });
  applyStrictLayerLocks(info);
  canvas.add(info);
}

